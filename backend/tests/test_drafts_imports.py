def _csv(*rows: str) -> dict:
    body = "\n".join(["name,login,role,unit_code", *rows]).encode()
    return {"file": ("staff.csv", body, "text/csv")}


def _login() -> str:
    return f"import{secrets.token_hex(4)}@example.com"


def test_staff_import_creates_good_lines_and_reports_bad_ones(sign_in, area):
    admin = staff(sign_in, "admin", area.division.id)  # scoped to one division
    elsewhere = tree()
    good, dup = _login(), _login()
    response = admin.post("/api/admin/accounts/import", files=_csv(
        f"Test AE One,{good},section_ae,{area.section_a.code}",
        f"Test AE Two,{dup},section_ae,{area.section_b.code}",
        f"Test AE Dup,{dup},section_ae,{area.section_b.code}",
        f"Test Consumer,{_login()},consumer,{area.section_a.code}",
        f"Test Ghost,{_login()},no_such_role,{area.section_a.code}",
        f"Test Owner,{_login()},super_admin,{area.section_a.code}",
        f"Test Away,{_login()},section_ae,{elsewhere.section_a.code}",
        f"Test Nowhere,{_login()},section_ae,NOPE{area.tag}",
        f"Test Bad Login,not-an-email,section_ae,{area.section_a.code}",
        f",{_login()},section_ae,{area.section_a.code}",
    ))
    assert response.status_code == 200, response.text
    assert response.headers["cache-control"] == "no-store"
    body = response.json()
    assert [(c["line"], c["login"], c["unit"]) for c in body["created"]] == [
        (2, good, area.section_a.name), (3, dup, area.section_b.name)]
    assert [e["line"] for e in body["errors"]] == list(range(4, 12))
    assert "already exists" in body["errors"][0]["detail"]
    assert "scope" in body["errors"][4]["detail"]  # a unit outside the importer's division

    password = body["created"][0]["password"]
    assert len(password) >= 16
    fresh = TestClient(app)
    assert fresh.post("/api/auth/login", json={"login": good, "password": password}).status_code == 200
    me = fresh.get("/api/auth/me").json()
    assert me["role"] == "section_ae" and [s["unit_id"] for s in me["scopes"]] == [area.section_a.id]

    with tx() as conn:
        rows = [dict(r) for r in conn.execute("SELECT action, target, detail FROM audit_log")]
    assert [r["detail"] for r in rows if r["action"] == "account.import"][-1] == "created 2, errors 8"
    every = " ".join(f"{r['target']} {r['detail']}" for r in rows)
    assert not any(c["password"] in every for c in body["created"])


def test_staff_import_limits_and_permission(sign_in, area):
    admin = staff(sign_in, "admin")
    assert admin.post("/api/admin/accounts/import",
                      files={"file": ("x.csv", b"name,login\nA,b@example.com", "text/csv")}).status_code == 400
    many = [f"N{i},{_login()},section_ae,{area.section_a.code}" for i in range(501)]
    assert admin.post("/api/admin/accounts/import", files=_csv(*many)).status_code == 413
    big = {"file": ("x.csv", b"name,login,role,unit_code\n" + b"x" * (1024 * 1024), "text/csv")}
    assert admin.post("/api/admin/accounts/import", files=big).status_code == 413
    officer = staff(sign_in, "officer", area.division.id)
    assert officer.post("/api/admin/accounts/import", files=_csv()).status_code == 403
