def test_misread_draft_is_priced_by_the_engine_and_can_be_recorded(reader, sign_in, area):
    ae = staff(sign_in, "section_ae", area.section_a.id)
    client = consumer(sign_in)
    march_bill = synthetic(*MARCH, section=area.section_a.name)
    march = upload(client, reader, march_bill)
    ticket = report(client, march["id"])
    april = upload(client, reader, synthetic(*APRIL, section=area.section_a.name))

    draft = ae.get(f"/api/review/cases/{ticket}/draft").json()
    expected = rules.corrected_reading(march_bill, 1150, Policy(discom="TGSPDCL"))
    assert draft["kind"] == "corrected_reading" and draft["corrected_present_reading"] == 1150
    assert draft["reason_code"] == "photo_misread" and draft["strength"] == "strong"
    assert draft["evidence"] == [{"kind": "bill", "id": march["id"]}, {"kind": "bill", "id": april["id"]}]
    assert draft["preview"] == {"corrected_units": expected.corrected_units, "revised_amount": expected.revised_amount,
                                "reduction": expected.reduction, "needs_approval": False}
    assert len(draft["note"]) >= 20 and len(draft["why"]) == 3

    body = {k: draft[k] for k in ("kind", "corrected_present_reading", "reason_code", "note", "evidence")}
    decided = ae.post(f"/api/review/cases/{ticket}/decisions", json=body)
    assert decided.status_code == 200, decided.text
    assert decided.json()["decisions"][0]["reduction"] == expected.reduction
    assert ae.get(f"/api/review/cases/{ticket}/draft").json() is None  # decided: nothing left to suggest


