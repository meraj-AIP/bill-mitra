def test_unmapped_names_suggest_close_sections_in_scope(sign_in, area):
    admin = staff(sign_in, "super_admin")
    near, far = f"Sectin A {area.tag}", f"Zzqx {secrets.token_hex(4)}"
    units.record_unmapped("TGSPDCL", near)
    units.record_unmapped("TGSPDCL", far)
    listed = {u["name"]: u for u in admin.get("/api/admin/units/unmapped").json()}
    suggested = listed[near]["suggestions"]
    assert suggested[0]["section_id"] == area.section_a.id and 0.8 <= suggested[0]["score"] <= 1
    assert len(suggested) <= 3 and all(s["score"] >= 0.8 for s in suggested)
    assert [s["score"] for s in suggested] == sorted((s["score"] for s in suggested), reverse=True)
    assert listed[far]["suggestions"] == []


