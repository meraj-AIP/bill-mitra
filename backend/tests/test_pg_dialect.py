"""The one SQL text per query works on both databases: the translation to Postgres, and SQLite's date functions
rebuilt in Postgres giving what SQLite gives."""

import sqlite3

import pytest

from app.store import db, pg


def test_placeholders_become_psycopg_ones_and_percent_signs_are_kept():
    sql = pg.translate("SELECT * FROM t WHERE a = ? AND b LIKE '%x?%' AND c = :me AND d = 'a:b'")
    assert sql == "SELECT * FROM t WHERE a = %s AND b ILIKE '%%x?%%' AND c = %(me)s AND d = 'a:b'"


def test_comments_and_literals_are_left_alone():
    sql = pg.translate("-- it's date(now)\nSELECT 'date(x) INTEGER' FROM t", params=False)
    assert sql == "-- it's date(now)\nSELECT 'date(x) INTEGER' FROM t"


def test_sqlite_functions_and_types_are_mapped():
    sql = pg.translate("SELECT datetime('now', ?), date(ts), julianday(a), strftime('%Y', b), instr(x, ?), "
                       "json_extract(e, '$.a'), CURRENT_TIMESTAMP, CAST(z AS REAL), group_concat(s) FROM t")
    assert "bm_datetime('now', %s)" in sql and "bm_date(ts)" in sql and "bm_julianday(a)" in sql
    assert "bm_strftime('%%Y', b)" in sql and "strpos(x, %s)" in sql and "bm_json_extract(e, '$.a')" in sql
    assert "bm_now()" in sql and "CAST(z AS DOUBLE PRECISION)" in sql and "string_agg(CAST(s AS TEXT), ',')" in sql
    assert "updated_at" in pg.translate("SELECT updated_at FROM t")  # a column ending in 'date' stays


def test_ddl_gets_identity_keys_and_wide_types():
    sql = pg.translate("CREATE TABLE x (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER, amount REAL, "
                       "ts TEXT DEFAULT CURRENT_TIMESTAMP)", params=False)
    assert sql == ("CREATE TABLE x (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT, "
                   "amount DOUBLE PRECISION, ts TEXT DEFAULT bm_now())")


def test_a_time_with_no_column_in_it_is_computed_once_per_statement():
    sql = pg.translate("SELECT date(ts, '+5 hours') FROM e WHERE ts >= date('now', :day) AND d < datetime('now', ?)")
    assert sql == ("SELECT bm_date(ts, '+5 hours') FROM e WHERE ts >= (SELECT bm_date('now', %(day)s)) "
                   "AND d < (SELECT bm_datetime('now', %s))")


def test_insert_or_ignore_becomes_on_conflict_before_returning():
    assert pg.translate("INSERT OR IGNORE INTO t (a) VALUES (?)") == "INSERT INTO t (a) VALUES (%s) ON CONFLICT DO NOTHING"
    assert pg.translate("INSERT OR IGNORE INTO t (a) VALUES (?) RETURNING id") == (
        "INSERT INTO t (a) VALUES (%s) ON CONFLICT DO NOTHING RETURNING id")


def test_day_counts_drop_the_fraction_and_empty_lists_still_parse():
    sql = pg.translate("SELECT CAST(julianday('now') - julianday(c.created_at) AS INTEGER) FROM c WHERE x IN ()")
    assert "CAST(trunc((SELECT bm_julianday('now')) - bm_julianday(c.created_at)) AS BIGINT)" in sql
    assert "IN (SELECT NULL WHERE 1 = 0)" in sql
    assert pg.translate("SELECT CAST(n AS INTEGER) FROM t") == "SELECT CAST(n AS BIGINT) FROM t"


def test_rows_read_by_position_or_by_name_like_sqlite():
    row = pg.Row((1, "a"), ["id", "role_name"], {"id": 0, "role_name": 1})
    assert row[0] == 1 and row["ROLE_NAME"] == "a" and dict(zip(row.keys(), row, strict=True)) == {
        "id": 1, "role_name": "a"}
    assert list(row) == [1, "a"] and len(row) == 2 and row[1:] == ("a",)


# Each expression in SQLite's dialect, run on both databases. Fixed times only, so the answers never move.
SAME_ANSWER = (
    "datetime('2026-03-31 10:00:00', '+1 day')",
    "datetime('2026-03-31 10:00:00', '-5 hours', '+30 minutes')",
    "date('2026-03-31 23:59:59')",
    "date('2026-03-15 10:00:00', 'start of month')",
    "datetime('2026-03-15T10:00:00+05:30')",
    "datetime('2026-03-15 10:00:00', '+' || 3 || ' days')",
    "CAST(julianday('2026-03-15 12:00:00') - julianday('2026-03-12 18:00:00') AS INTEGER)",
    "strftime('%Y-%m', '2026-03-15 10:00:00')",
    "datetime('not a date')",
    "date('2026-03-15 10:00:00', '+1 month', '-1 day')",
    "datetime('2026-03-15 10:00:00', '+1.5 days')",
    "date('2026-03-15')",
    "julianday('2026-03-15T10:00:00Z')",
    "json_extract('{\"a\": {\"b\": \"x\"}}', '$.a.b')",
    "CAST(json_extract('{\"n\": 12.5}', '$.n') AS REAL)",
    "instr(upper('Kukatpally'), 'PALLY')",
    "round(2.345, 1)",
)


@pytest.mark.skipif(not db.is_postgres(), reason="needs TEST_DATABASE_URL")
@pytest.mark.parametrize("expression", SAME_ANSWER)
def test_postgres_gives_what_sqlite_gives(expression: str):
    expected = sqlite3.connect(":memory:").execute(f"SELECT {expression}").fetchone()[0]
    with db.tx() as conn:
        assert conn.execute(f"SELECT {expression}").fetchone()[0] == expected


@pytest.mark.skipif(not db.is_postgres(), reason="needs TEST_DATABASE_URL")
def test_postgres_counts_true_conditions_and_reads_json_lists():
    with db.tx() as conn:
        assert conn.execute("SELECT SUM(x > 1) FROM (SELECT 1 AS x UNION ALL SELECT 2 UNION ALL SELECT 3) t"
                            ).fetchone()[0] == 2
        assert [r[0] for r in conn.execute("SELECT value FROM json_each(?)", ('["a", "b"]',))] == ["a", "b"]
        assert conn.execute("SELECT SUM(n), AVG(n) FROM (SELECT 1 AS n UNION ALL SELECT 2) t").fetchone()[:] == (3, 1.5)


@pytest.mark.skipif(not db.is_postgres(), reason="needs TEST_DATABASE_URL")
def test_sqlite_database_copies_into_postgres_keeping_ids_and_order(tmp_path, monkeypatch: pytest.MonkeyPatch):
    import psycopg

    from app.config import get_settings
    from app.tools import sqlite_to_postgres

    url = get_settings().database_url
    with psycopg.connect(url, autocommit=True) as admin:
        admin.execute("DROP SCHEMA IF EXISTS copy_test CASCADE")
        admin.execute("CREATE SCHEMA copy_test")
    path = tmp_path / "old.db"
    source = sqlite3.connect(path)
    db._build(source)
    source.execute("INSERT INTO complaints (ticket, user_id, issue, status, amount, created_at) "
                   "VALUES ('BM-COPY-1', 'web:x', 'old', 'Open', 120.5, '2026-01-02 03:04:05')")
    source.execute("INSERT INTO complaint_messages (id, ticket, author_kind, body, delivery) "
                   "VALUES (41, 'BM-COPY-1', 'consumer', 'hello', 'not_applicable')")
    source.execute("UPDATE roles SET description = 'edited before the move' WHERE slug = 'officer'")
    source.commit()
    source.close()

    saved = db._conn, db._pg, db._pool
    monkeypatch.setattr(get_settings(), "database_url", f"{url}?options=-csearch_path%3Dcopy_test")
    db._conn, db._pg, db._pool = None, None, None
    try:
        counts = sqlite_to_postgres.copy(path)
        assert counts["complaints"] == 1 and counts["complaint_messages"] == 1
        with db.tx() as conn:
            row = conn.execute("SELECT amount, created_at FROM complaints WHERE ticket = 'BM-COPY-1'").fetchone()
            assert row[:] == (120.5, "2026-01-02 03:04:05")
            assert conn.execute("SELECT description FROM roles WHERE slug = 'officer'").fetchone()[0] == (
                "edited before the move")
            new_id = conn.execute("INSERT INTO complaint_messages (ticket, author_kind, body, delivery) VALUES "
                                  "('BM-COPY-1', 'staff', 'reply', 'sent') RETURNING id").fetchone()[0]
            assert new_id == 42  # the sequence moved past the copied ids
        with pytest.raises(SystemExit, match="already has rows"):
            sqlite_to_postgres.copy(path)
    finally:
        db.reset_for_tests()
        db._conn, db._pg, db._pool = saved
